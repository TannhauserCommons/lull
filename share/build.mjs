// The Worker's static files (docs/adr/0034), gathered into public/ from where each one lives, so nothing is copied
// into the repository twice: the open page and its script and style (site/, also GitHub Pages' copy for older
// links), lull's icon and font (web/), lull's card (the app's own fallback art), Android's App Links statement
// (packaging/android/) and robots.txt (static/). Run by wrangler before every dev, test and deploy build, and by
// .github/workflows/pages.yml for GitHub Pages' copy of the open page.
//
// It also writes the page's looks (ADR-0034, "The page in the sharer's design"), from the app's own CSS:
// - look.css: lull's base tokens (web/tokens.css), what every page uses;
// - look/<design>.css: a built-in design's colour tokens, day and night, and the faces of its UI font, which a link's
//   `d=<design>` adds; look/designs.json: each design's name and accent, for the Worker.
// The app switches day and night with data-theme; a share page follows the viewer's own setting instead, so the night
// blocks become prefers-color-scheme rules: no script, no flash of the day colours.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const out = new URL('public/', import.meta.url);
const files = {
  'open.html': 'site/open.html',
  'open.css': 'site/open.css',
  'open.js': 'site/open.js',
  'app-icon.svg': 'web/assets/app-icon.svg',
  'nunito-latin.woff2': 'web/fonts/nunito-latin.woff2',
  'lull-card.png': 'web/assets/fallback-art-512.png',
  '.well-known/assetlinks.json': 'packaging/android/assetlinks.json',
  'robots.txt': 'share/static/robots.txt',
};

rmSync(out, { recursive: true, force: true });
mkdirSync(new URL('.well-known/', out), { recursive: true });
mkdirSync(new URL('look/', out), { recursive: true });
for (const [to, from] of Object.entries(files)) cpSync(new URL(from, root), new URL(to, out));

const read = (path) => readFileSync(new URL(path, root), 'utf8');
writeFileSync(new URL('look.css', out), baseLook(read('web/tokens.css')));
const designs = {};
for (const id of readdirSync(new URL('web/designs/', root))) {
  if (!existsSync(new URL(`web/designs/${id}/theme.json`, root))) continue;
  const manifest = JSON.parse(read(`web/designs/${id}/theme.json`));
  writeFileSync(new URL(`look/${id}.css`, out), designLook(id, read(`web/designs/${id}/theme.css`)));
  designs[id] = { name: manifest.name, accent: manifest.swatches[2] };
}
writeFileSync(new URL('look/designs.json', out), JSON.stringify(designs, null, 2) + '\n');

/** web/tokens.css with its night block following the viewer's setting. */
function baseLook(css) {
  const night = ':root[data-theme="night"]';
  const body = block(css, night);
  if (body === null) throw new Error(`web/tokens.css has no ${night} block`);
  const at = css.indexOf(night + ' {');
  const end = at + (night + ' {').length + body.length + 1;
  return '/* generated by share/build.mjs from web/tokens.css: lull\'s base tokens for the share page */\n' +
    css.slice(0, at) + `@media (prefers-color-scheme: dark) { :root {${body}} }` + css.slice(end);
}

/** A design's colour tokens, day and night, and the faces of its UI font (`--f-ui`), copied beside the CSS. */
function designLook(id, css) {
  const selector = `:root[data-design="${id}"]`;
  const day = block(css, selector), night = block(css, `${selector}[data-theme="night"]`);
  if (day === null) throw new Error(`web/designs/${id}/theme.css has no ${selector} block`);
  const ui = /--f-ui:\s*([^;]+);/.exec(day)?.[1] || '';
  const faces = [...css.matchAll(/@font-face\s*\{[^}]*\}/g)].map((m) => m[0]).filter((face) => {
    const family = /font-family:\s*"([^"]+)"/.exec(face)?.[1];
    return family && ui.includes(`"${family}"`);
  }).map((face) => face.replace(/url\("assets\/fonts\/([^"]+)"\)/g, (_, file) => {
    mkdirSync(new URL(`look/${id}/`, out), { recursive: true });
    cpSync(new URL(`web/designs/${id}/assets/fonts/${file}`, root), new URL(`look/${id}/${file}`, out));
    return `url("${id}/${file}")`;
  }));
  return `/* generated by share/build.mjs from web/designs/${id}/theme.css: its tokens and UI font, for the share page */\n` +
    '@layer design {\n' +
    faces.map((f) => f + '\n').join('') +
    `${selector} {\n${tokens(day)}}\n` +
    (night === null ? '' : `@media (prefers-color-scheme: dark) { ${selector} {\n${tokens(night)}} }\n`) +
    '}\n';
}

/** The custom properties a block sets, but not the ones naming a file: the page draws no design's pictures. */
function tokens(body) {
  return [...body.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)]
    .filter((m) => !m[2].includes('url('))
    .map((m) => `  ${m[1]}: ${m[2].trim()};\n`).join('');
}

/** The body of the first `selector { … }` in `css`, or null. */
function block(css, selector) {
  const at = css.indexOf(selector + ' {');
  if (at < 0) return null;
  const open = at + selector.length + 1;
  for (let i = open, depth = 0; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}' && --depth === 0) return css.slice(open + 1, i);
  }
  return null;
}
